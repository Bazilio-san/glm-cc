// Storage layer for the glm configuration.
//
// Two files, both in the user's home directory and both owned entirely by glm:
//   ~/.glm-claude-code.json  source of truth, human-readable, edited by `glm -c`
//   ~/.glm-claude-code.env   flat KEY=VALUE sidecar that glm.cmd / glm.sh read
//                            at every launch without starting Node
//
// Claude Code's own files (~/.claude/settings.json, ~/.claude.json) are never
// read for writing and never modified: glm only ever exports environment
// variables into the process it launches.

import fs from 'node:fs';
import os from 'node:os';
import path from 'node:path';

export const JSON_PATH = path.join(os.homedir(), '.glm-claude-code.json');
export const ENV_PATH = path.join(os.homedir(), '.glm-claude-code.env');

/**
 * Every variable glm knows how to manage, in the order they are written to the
 * env file. `label` is what the user sees; `secret` values are masked on screen.
 */
export const FIELDS = [
  {
    key: 'ANTHROPIC_BASE_URL',
    label: 'API endpoint',
    describe: 'Anthropic-compatible server Claude Code talks to',
    default: 'https://api.z.ai/api/anthropic',
    required: true,
  },
  {
    key: 'ANTHROPIC_AUTH_TOKEN',
    label: 'API key',
    describe: 'Bearer token sent with every request',
    default: '',
    required: true,
    secret: true,
  },
  {
    key: 'ANTHROPIC_DEFAULT_SONNET_MODEL',
    label: 'Main model (Sonnet slot)',
    describe: 'Model used for ordinary work',
    default: 'glm-5.3[1m]',
    required: true,
  },
  {
    key: 'ANTHROPIC_DEFAULT_OPUS_MODEL',
    label: 'Main model (Opus slot)',
    describe: 'Model used when Claude Code asks for its strongest model',
    default: 'glm-5.3[1m]',
    required: true,
  },
  {
    key: 'ANTHROPIC_DEFAULT_HAIKU_MODEL',
    label: 'Small model (Haiku slot)',
    describe: 'Model used for cheap background tasks',
    default: 'glm-5.3-flash[1m]',
    required: true,
  },
  {
    key: 'API_TIMEOUT_MS',
    label: 'Request timeout',
    describe: 'Milliseconds Claude Code waits for a reply before giving up',
    default: '3000000',
    required: false,
  },
  {
    key: 'CLAUDE_CODE_DISABLE_NONESSENTIAL_TRAFFIC',
    label: 'Non-essential traffic',
    describe: 'Set to 1 to switch off optional telemetry and update pings',
    default: '1',
    required: false,
  },
  {
    key: 'CLAUDE_CODE_AUTO_COMPACT_WINDOW',
    label: 'Auto-compact window',
    describe: 'Token count at which the conversation gets compacted',
    default: '1048576',
    required: false,
  },
];

export const DEFAULTS = Object.fromEntries(FIELDS.map(f => [f.key, f.default]));
export const REQUIRED_KEYS = FIELDS.filter(f => f.required).map(f => f.key);

export function fieldFor (key) {
  return FIELDS.find(f => f.key === key) || null;
}

/** Read the stored configuration. Missing or broken file yields an empty object. */
export function load () {
  try {
    const parsed = JSON.parse(fs.readFileSync(JSON_PATH, 'utf-8'));
    return parsed && typeof parsed === 'object' ? parsed : {};
  } catch {
    return {};
  }
}

/**
 * Stored values with defaults filled in for anything the user has never set.
 *
 * A key stored as an empty string is not "unset" — it is an explicit "do not
 * export this variable at all", so the default must not creep back in.
 */
export function effective (config = load()) {
  const merged = { ...DEFAULTS };
  for (const [key, value] of Object.entries(config)) {
    if (value != null) merged[key] = String(value);
  }
  return merged;
}

export function isComplete (config = load()) {
  return REQUIRED_KEYS.every(key => {
    const value = config[key] ?? DEFAULTS[key];
    return value != null && String(value).trim() !== '';
  });
}

export function missingKeys (config = load()) {
  return REQUIRED_KEYS.filter(key => {
    const value = config[key] ?? DEFAULTS[key];
    return value == null || String(value).trim() === '';
  });
}

function writeJson (config) {
  // Keep a stable key order so the file stays reviewable in a diff.
  const ordered = {};
  for (const field of FIELDS) {
    if (config[field.key] != null) ordered[field.key] = String(config[field.key]);
  }
  for (const [key, value] of Object.entries(config)) {
    if (!(key in ordered) && value != null) ordered[key] = String(value);
  }
  fs.writeFileSync(JSON_PATH, `${JSON.stringify(ordered, null, 2)}\n`, 'utf-8');
}

function writeEnv (config) {
  const values = effective(config);
  const header = [
    // Plain ASCII only: cmd.exe reads this file under whatever code page the
    // console happens to be using.
    '# Generated by @bazilio-san/glm-cc - do not edit by hand.',
    '# Change these values with `glm -c`.',
    '# Read by bin/glm.cmd and bin/glm.sh, then exported into `claude`.',
  ];
  const body = FIELDS
    // An empty value means "leave this variable unset" rather than "set it to
    // an empty string", so those lines are omitted entirely.
    .filter(field => String(values[field.key] ?? '').trim() !== '')
    .map(field => `${field.key}=${values[field.key]}`);
  fs.writeFileSync(ENV_PATH, `${[...header, ...body].join('\n')}\n`, 'utf-8');
}

/** Persist to both files at once — they must never drift apart. */
export function save (config) {
  writeJson(config);
  writeEnv(config);
}

/** Regenerate only the env sidecar from the stored JSON. */
export function refreshEnv () {
  writeEnv(load());
}

/** Delete both files. Returns the paths that actually existed. */
export function removeAll () {
  const removed = [];
  for (const file of [JSON_PATH, ENV_PATH]) {
    if (fs.existsSync(file)) {
      fs.unlinkSync(file);
      removed.push(file);
    }
  }
  return removed;
}

export function exists () {
  return fs.existsSync(JSON_PATH);
}

/** Show only the first and last few characters of a secret. */
export function maskSecret (value) {
  if (!value) return '';
  const s = String(value);
  if (s.length <= 10) return `${s.slice(0, 2)}${'•'.repeat(Math.max(2, s.length - 2))}`;
  return `${s.slice(0, 4)}${'•'.repeat(8)}${s.slice(-4)}`;
}
